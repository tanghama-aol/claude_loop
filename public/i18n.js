    function normalizeLanguage(value) {
        return String(value || "").toLowerCase().startsWith("en") ? "en" : DEFAULT_LANGUAGE;
    }

    function interpolate(template, params = {}) {
        return String(template).replace(/\{\{(\w+)\}\}/g, (match, key) => (
            Object.hasOwn(params, key) ? String(params[key]) : match
        ));
    }

    function translate(language, key, params = {}) {
        const normalized = normalizeLanguage(language);
        const template = messages[normalized]?.[key] ?? messages[DEFAULT_LANGUAGE]?.[key] ?? key;
        return interpolate(template, params);
    }

    function createI18n({ storage = null, navigatorLanguage = "", documentRef = null } = {}) {
        let savedLanguage = "";
        try {
            savedLanguage = storage?.getItem(STORAGE_KEY) || "";
        } catch {
            savedLanguage = "";
        }
        let language = normalizeLanguage(savedLanguage || navigatorLanguage || DEFAULT_LANGUAGE);

        function t(key, params = {}) {
            return translate(language, key, params);
        }

        function count(key, value, params = {}) {
            const suffix = value === 1 ? "one" : "other";
            return t(`${key}.${suffix}`, { ...params, count: value });
        }

        function apply(root = documentRef) {
            if (!root) return;
            if (documentRef?.documentElement) documentRef.documentElement.lang = language;
            root.querySelectorAll("[data-i18n]").forEach((node) => {
                node.textContent = t(node.dataset.i18n);
            });
            root.querySelectorAll("[data-i18n-placeholder]").forEach((node) => {
                node.placeholder = t(node.dataset.i18nPlaceholder);
            });
            root.querySelectorAll("[data-i18n-aria-label]").forEach((node) => {
                node.setAttribute("aria-label", t(node.dataset.i18nAriaLabel));
            });
            root.querySelectorAll("[data-i18n-title]").forEach((node) => {
                node.title = t(node.dataset.i18nTitle);
            });
        }

        function setLanguage(value, { persist = true } = {}) {
            language = normalizeLanguage(value);
            if (persist) {
                try {
                    storage?.setItem(STORAGE_KEY, language);
                } catch {
                    // Storage may be unavailable in privacy-restricted contexts.
                }
            }
            apply();
            return language;
        }

        return {
            apply,
            count,
            getLanguage: () => language,
            getLocale: () => language === "en" ? "en-US" : "zh-CN",
            setLanguage,
            t,
        };
    }

    return {
        DEFAULT_LANGUAGE,
        STORAGE_KEY,
        createI18n,
        messages,
        normalizeLanguage,
        translate,
    };
